package com.mayacardio.pipeline.tools;

import com.fasterxml.jackson.databind.JsonNode;
import com.mayacardio.pipeline.core.Json;

import java.io.IOException;
import java.nio.file.DirectoryStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Iterator;
import java.util.List;
import java.util.Map;

public final class Summarize {
    private static final String[] METRICS = {
            "ms_cut_to_offline", "ms_restore_to_online", "ms_restore_to_cloud_copy_complete", "outage_seconds",
            "backlog_at_restore", "samples_backlog_at_restore", "http_bytes_sent_during_catchup", "offline_results_written",
            "worst_seconds_lost", "stated_bound_seconds", "ms_to_detect_disk_full", "pending_in_memory_while_full",
            "ms_to_recover_after_space_freed", "daemon_survived", "no_spurious_mode_switch", "hold_seconds",
            "simulated_outage_data_minutes", "generation_speed_while_offline", "mock_buffer_seconds_of_data", "skipped", "error"};

    private Summarize() {
    }

    public static void main(String[] args) throws Exception {
        Path dir = Path.of(args.length > 0 ? args[0] : "evidence");
        List<Path> files = new ArrayList<>();
        try (DirectoryStream<Path> ds = Files.newDirectoryStream(dir, "*.json")) {
            ds.forEach(files::add);
        }
        files.sort(null);
        StringBuilder md = new StringBuilder();
        md.append("# Failure-test evidence\n\n");
        md.append("Generated by `java -jar dist/pipeline-tools.jar summarize evidence` from the JSON files in this directory. ");
        md.append("Every run used the **stand-in** mock and checker (not the official tools). Raw logs and databases of each run are in `evidence/raw/` (not committed).\n\n");
        md.append("Environment: `baseline`, `kill9`, `netcut`, `mockfaults`, `powercut`, `backlog` ran on the development machine (Windows 11, x86-64, JDK 21; device, mock and cloud as separate processes, the cloud using SQLite behind a TCP proxy that black-holes traffic for network cuts). ");
        md.append("`diskfull-*` and `clock` ran in a Linux container (amd64, JDK 17) because they need a small tmpfs and `CAP_SYS_TIME`. ");
        md.append("Full JSON per scenario (timelines, every check) is in the scenario's `.json` file.\n\n");
        md.append("How to read the columns: *declared* lists losses the device recorded, by reason, in samples; *silent* is samples neither saved nor declared (must be 0). ");
        md.append("*not verifiable* results are the last window or two whose inputs extend beyond the moment the export was taken. ");
        md.append("In `mockfaults` the `buffer_overflow` losses come from the injected 15 s mock stall (longer than the mock's 10 s buffer), `sensor_outage` from the injected outages and the unread tail from the injected mock restart. ");
        md.append("In `diskfull-beyond-buffer` the memory buffer was reduced to 8,000 samples per sensor (20 s) and the disk held full for 45 s, so the oldest ~27 s per sensor were dropped and declared `disk_full`. ");
        md.append("In `backlog` the stand-in's buffer was set to 200 s of data because data was generated at 20x speed (200 s of data = 10 s of wall time).\n\n");
        md.append("| Scenario | Result | Key measurements | Ground truth (per session) | Device = cloud | Results vs reference |\n");
        md.append("|---|---|---|---|---|---|\n");
        for (Path f : files) {
            JsonNode n = Json.read(Files.readString(f));
            if (!n.has("scenario")) {
                continue;
            }
            md.append("| ").append(n.get("scenario").asText()).append(" | ")
                    .append(n.path("pass").asBoolean(false) ? "PASS" : "FAIL").append(" | ")
                    .append(metrics(n)).append(" | ")
                    .append(ground(n)).append(" | ")
                    .append(compare(n)).append(" | ")
                    .append(results(n)).append(" |\n");
        }
        md.append("\nLatency (online windows, `computed_at` minus the time the window's last sample was generated, windows near disruptions excluded):\n\n");
        for (Path f : files) {
            JsonNode n = Json.read(Files.readString(f));
            for (String k : new String[]{"online_latency", "online_latency_outside_outage"}) {
                JsonNode l = n.get(k);
                if (l != null) {
                    md.append("- ").append(n.get("scenario").asText()).append(": ").append(l.path("windows_measured").asLong())
                            .append(" windows, p50 ").append(l.path("p50_ms").asLong()).append(" ms, p95 ")
                            .append(l.path("p95_ms").asLong()).append(" ms, max ").append(l.path("max_ms").asLong())
                            .append(" ms, over 5 s: ").append(l.path("windows_over_5s").asLong()).append("\n");
                }
            }
        }
        Path res = dir.resolve("resources");
        if (Files.isDirectory(res)) {
            md.append("\n## Resource figures\n\n| Run | Seconds | CPU % of one core | CPU % of all cores | Peak RSS MB | MB written/hour | MB sent/hour (interface) |\n|---|---|---|---|---|---|---|\n");
            List<Path> rf = new ArrayList<>();
            try (DirectoryStream<Path> ds = Files.newDirectoryStream(res, "*.json")) {
                ds.forEach(rf::add);
            }
            rf.sort(null);
            for (Path f : rf) {
                JsonNode n = Json.read(Files.readString(f));
                double sec = n.path("measured_seconds").asDouble();
                md.append("| ").append(f.getFileName().toString().replace(".json", "")).append(" | ").append(Math.round(sec))
                        .append(" | ").append(n.path("pipeline_avg_cpu_percent_of_one_core").asDouble())
                        .append(" | ").append(String.format("%.2f", n.path("pipeline_avg_cpu_percent_of_one_core").asDouble() / 4))
                        .append(" (of 4) | ").append(n.path("pipeline_peak_rss_mb_sampled").asDouble())
                        .append(" | ").append(n.path("pipeline_mb_written_per_hour").asDouble())
                        .append(" | ").append(String.format("%.1f", n.path("iface_mb_sent").asDouble() * 3600 / sec)).append(" |\n");
            }
        }
        Path out = dir.resolve("SUMMARY.md");
        Files.writeString(out, md.toString());
        System.out.println("wrote " + out);
    }

    private static String metrics(JsonNode n) {
        List<String> parts = new ArrayList<>();
        for (String k : METRICS) {
            if (n.has(k) && !n.get(k).isNull()) {
                JsonNode v = n.get(k);
                parts.add(k + "=" + (v.isNumber() ? v.decimalValue().stripTrailingZeros().toPlainString() : v.asText()));
            }
        }
        if (n.has("kills")) {
            List<String> ks = new ArrayList<>();
            for (JsonNode k : n.get("kills")) {
                ks.add(k.path("ms_from_restart_to_collecting_past_kill_point").asText() + " ms");
            }
            parts.add("restart_to_collecting=" + ks);
        }
        if (n.has("device_counters")) {
            parts.add("counters=" + n.get("device_counters").toString().replace("\"", "").replace("|", "/"));
        }
        return String.join("<br>", parts);
    }

    private static Iterable<Map.Entry<String, JsonNode>> sessions(JsonNode n) {
        List<Map.Entry<String, JsonNode>> out = new ArrayList<>();
        JsonNode checks = n.get("checks");
        if (checks == null) {
            return out;
        }
        Iterator<Map.Entry<String, JsonNode>> it = checks.fields();
        while (it.hasNext()) {
            Map.Entry<String, JsonNode> e = it.next();
            if (e.getValue().isObject() && e.getValue().has("ground_truth_check")) {
                out.add(e);
            }
        }
        return out;
    }

    private static String ground(JsonNode n) {
        List<String> parts = new ArrayList<>();
        for (Map.Entry<String, JsonNode> e : sessions(n)) {
            JsonNode g = e.getValue().get("ground_truth_check");
            if (!g.isObject()) {
                parts.add(e.getKey() + ": " + g.asText());
                continue;
            }
            StringBuilder sb = new StringBuilder(e.getKey()).append(g.path("pass").asBoolean() ? " ok" : " FAIL").append(": ");
            for (String s : new String[]{"sensor_1", "sensor_2"}) {
                JsonNode x = g.get(s);
                sb.append("s").append(s.charAt(7)).append(" saved ").append(x.path("samples_exported").asLong())
                        .append(", silent ").append(x.path("silent_loss_samples").asLong())
                        .append(", dup ").append(x.path("duplicates").asLong())
                        .append(", wrong ").append(x.path("wrong_values").asLong())
                        .append(", declared ").append(x.path("declared_lost_by_reason").toString().replace("\"", ""))
                        .append("; ");
            }
            parts.add(sb.toString());
        }
        return String.join("<br>", parts);
    }

    private static String compare(JsonNode n) {
        List<String> parts = new ArrayList<>();
        for (Map.Entry<String, JsonNode> e : sessions(n)) {
            JsonNode c = e.getValue().get("device_vs_cloud");
            parts.add(c.isObject() ? (c.path("identical").asBoolean() ? "identical" : "DIFFERENT") : c.asText());
        }
        return String.join("<br>", parts);
    }

    private static String results(JsonNode n) {
        List<String> parts = new ArrayList<>();
        for (Map.Entry<String, JsonNode> e : sessions(n)) {
            JsonNode r = e.getValue().get("results_check");
            StringBuilder sb = new StringBuilder();
            for (String m : new String[]{"online", "offline"}) {
                if (r.has(m)) {
                    sb.append(m).append(" ").append(r.get(m).path("matched").asLong()).append("/")
                            .append(r.get(m).path("results").asLong()).append(" matched, ")
                            .append(r.get(m).path("mismatched").asLong()).append(" mismatched, ")
                            .append(r.get(m).path("not_verifiable_beyond_export").asLong()).append(" not verifiable; ");
                }
            }
            parts.add(sb.toString());
        }
        return String.join("<br>", parts);
    }
}
